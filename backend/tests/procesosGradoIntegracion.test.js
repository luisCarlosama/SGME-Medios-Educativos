import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { test } from 'node:test';
import dotenv from 'dotenv';
import pg from 'pg';

const backend = dirname(dirname(fileURLToPath(import.meta.url)));

test('flujo ficticio aislado: periodo, selección, asistencia, errores y reintento', {
  skip: process.env.PROCESOS_GRADO_TEST_INTEGRACION !== 'true',
  timeout: 60000,
}, async () => {
  dotenv.config({ path: join(backend, '.env') });
  assert.ok(['localhost', '127.0.0.1', '::1'].includes(process.env.DB_HOST));
  const suffix = randomBytes(8).toString('hex');
  const appName = `sgme_app_prueba_${suffix}`;
  const mockName = `sgme_grados_prueba_${suffix}`;
  const options = {
    host: process.env.DB_HOST,
    port: Number(process.env.DB_PORT || 5432),
    user: process.env.DB_USER,
    password: process.env.DB_PASSWORD,
    database: process.env.DB_NAME,
    connectionTimeoutMillis: 10000,
  };
  const admin = new pg.Pool(options);
  let appCreated = false;
  let mockCreated = false;
  let app;
  let mock;
  let servicePool;
  let fakePool;
  try {
    await admin.query(`CREATE DATABASE ${pg.escapeIdentifier(appName)}`);
    appCreated = true;
    await admin.query(`CREATE DATABASE ${pg.escapeIdentifier(mockName)}`);
    mockCreated = true;
    app = new pg.Pool({ ...options, database: appName });
    mock = new pg.Pool({ ...options, database: mockName });
    await app.query(`
      CREATE TABLE public.ceremonia_grado (
        id_ceremonia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nombre TEXT NOT NULL, fecha DATE NOT NULL, estado TEXT NOT NULL,
        max_invitados_por_graduando INTEGER DEFAULT 2, cupo_invitados INTEGER DEFAULT 2
      );
      CREATE TABLE public.programa (id_programa INTEGER PRIMARY KEY, nombre TEXT NOT NULL, estado BOOLEAN NOT NULL);
      CREATE TABLE public.sesion (
        id_sesion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_ceremonia INTEGER NOT NULL REFERENCES public.ceremonia_grado,
        numero_sesion INTEGER NOT NULL, nombre TEXT NOT NULL, estado TEXT NOT NULL,
        hora_inicio TIME, hora_fin TIME
      );
      CREATE TABLE public.graduando (
        id_graduando INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_ceremonia INTEGER NOT NULL REFERENCES public.ceremonia_grado,
        id_sesion INTEGER REFERENCES public.sesion, nombres TEXT NOT NULL,
        apellidos TEXT NOT NULL, identificacion TEXT NOT NULL, codigo_estudiantil TEXT
      );
      CREATE TABLE public.graduando_programa (
        id_graduando INTEGER NOT NULL REFERENCES public.graduando,
        id_programa INTEGER NOT NULL REFERENCES public.programa
      );
      CREATE TABLE public.control_ingreso (
        id_sesion INTEGER NOT NULL REFERENCES public.sesion,
        id_graduando INTEGER REFERENCES public.graduando,
        id_invitado INTEGER,
        ingreso BOOLEAN NOT NULL
      );
      CREATE TABLE public.invitado (
        id_invitado INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_graduando INTEGER NOT NULL REFERENCES public.graduando
      );
      INSERT INTO public.programa VALUES (1, 'Programa ficticio', TRUE);
    `);
    const migracion = await readFile(join(backend, 'migrations', '007_periodo_y_procesos_grado.sql'), 'utf8');
    await app.query(migracion);
    await app.query(migracion);
    const migracionSesiones = await readFile(join(backend, 'migrations', '008_sesion_estado_manual.sql'), 'utf8');
    await app.query(migracionSesiones);
    await app.query(migracionSesiones);
    Object.assign(process.env, {
      DB_NAME: appName,
      GRADO_PRUEBA_HABILITADA: 'true',
      GRADO_PRUEBA_DB_HOST: options.host,
      GRADO_PRUEBA_DB_PORT: String(options.port),
      GRADO_PRUEBA_DB_NAME: mockName,
      GRADO_PRUEBA_DB_USER: options.user,
      GRADO_PRUEBA_DB_PASSWORD: options.password,
      NODE_ENV: 'development',
    });
    const ejecutarScript = (nombre) => {
      const resultado = spawnSync(process.execPath, [join(backend, nombre)], {
        cwd: backend, env: process.env, encoding: 'utf8',
      });
      assert.equal(resultado.status, 0, resultado.stderr);
    };
    ejecutarScript('crearProcesosGradoPrueba.js');
    const controller = await import('../src/controllers/procesosGradoPruebaController.js');
    const operaciones = await import('../src/controllers/ceremoniasOperacionesController.js');
    const scheduler = await import('../src/services/sesionesScheduler.js');
    const sync = await import('../src/services/sincronizacionGradosPrueba.js');
    servicePool = (await import('../src/db.js')).default;
    fakePool = (await import('../src/dbProcesosPrueba.js')).obtenerPoolProcesosPrueba();
    const res = () => ({
      statusCode: 200,
      status(code) { this.statusCode = code; return this; },
      json(body) { this.body = body; return this; },
      set() { return this; },
    });
    const request = (id, body = {}) => ({ params: { id: String(id) }, body, socket: { remoteAddress: '127.0.0.1' } });
    const ceremonia = await app.query(
      `INSERT INTO public.ceremonia_grado (nombre, fecha, estado, periodo_grado, finalizar_automaticamente)
       VALUES ('Prueba', CURRENT_DATE + 1, 'Programada', '2026-2', TRUE) RETURNING id_ceremonia`,
    );
    const id = ceremonia.rows[0].id_ceremonia;
    const anterior = await app.query(
      `INSERT INTO public.ceremonia_grado (nombre, fecha, estado)
       VALUES ('Anterior', CURRENT_DATE - 1, 'En curso') RETURNING id_ceremonia`,
    );
    await app.query(
      `INSERT INTO public.sesion (id_ceremonia, numero_sesion, nombre, estado, hora_inicio, hora_fin)
       VALUES ($1, 1, 'Anterior', 'En curso', '08:00', '09:00')`,
      [anterior.rows[0].id_ceremonia],
    );
    let response = res();
    await controller.guardarEstadoCatalogo(request(id, { nombre: 'Titulado', elegible: true }), response);
    assert.equal(response.statusCode, 400);
    response = res();
    await controller.guardarEstadoCatalogo(request(id, { nombre: 'Aprobado', elegible: true }), response);
    assert.equal(response.statusCode, 200);
    await mock.query("UPDATE public.proceso_grado_prueba SET estado = 'Aprobado' WHERE id_proceso = 'ficticio-pregrado-2'");
    response = res();
    await controller.listarCandidatosPrueba(request(id), response);
    assert.equal(response.statusCode, 200);
    assert.deepEqual(response.body.map((item) => item.id).sort(), ['ficticio-posgrado-1', 'ficticio-pregrado-2']);
    await mock.query("UPDATE public.proceso_grado_prueba SET estado = 'Pendiente' WHERE id_proceso = 'ficticio-pregrado-2'");
    response = res();
    await controller.listarCandidatosPrueba({ ...request(id), socket: { remoteAddress: '192.0.2.1' } }, response);
    assert.equal(response.statusCode, 403);

    for (const procesoId of ['ficticio-posgrado-1', 'ficticio-pregrado-2']) {
      response = res();
      await controller.agregarCandidatoPrueba(request(id, { procesoId, programaId: 1 }), response);
      assert.equal(response.statusCode, 201);
    }
    response = res();
    await controller.agregarCandidatoPrueba(request(id, { procesoId: 'ficticio-posgrado-1', programaId: 1 }), response);
    assert.equal(response.statusCode, 409);

    await app.query(
      `INSERT INTO public.sesion (id_ceremonia, numero_sesion, nombre, estado, hora_inicio, hora_fin)
       VALUES ($1, 1, 'Primera', 'Finalizada', '07:00', '08:00')`, [id],
    );
    const sesion = await app.query(
      `INSERT INTO public.sesion (id_ceremonia, numero_sesion, nombre, estado, hora_inicio, hora_fin)
       VALUES ($1, 2, 'Última', 'En curso', '08:00', '09:00') RETURNING id_sesion`, [id],
    );
    const graduandos = await app.query('SELECT id_graduando FROM public.graduando ORDER BY id_graduando');
    await app.query('UPDATE public.graduando SET id_sesion = $1 WHERE id_ceremonia = $2', [sesion.rows[0].id_sesion, id]);
    await app.query(
      'INSERT INTO public.control_ingreso (id_sesion, id_graduando, ingreso) VALUES ($1, $2, TRUE)',
      [sesion.rows[0].id_sesion, graduandos.rows[0].id_graduando],
    );
    await app.query("UPDATE public.ceremonia_grado SET estado = 'En curso' WHERE id_ceremonia = $1", [id]);
    await scheduler.actualizarEstadosPorHorario();
    assert.equal((await app.query('SELECT estado FROM public.ceremonia_grado WHERE id_ceremonia = $1', [id])).rows[0].estado, 'En curso');
    await app.query('UPDATE public.ceremonia_grado SET fecha = CURRENT_DATE - 1 WHERE id_ceremonia = $1', [id]);
    await scheduler.actualizarEstadosPorHorario();
    assert.equal((await app.query('SELECT estado FROM public.ceremonia_grado WHERE id_ceremonia = $1', [id])).rows[0].estado, 'Finalizada');
    assert.equal((await app.query('SELECT estado FROM public.ceremonia_grado WHERE id_ceremonia = $1', [anterior.rows[0].id_ceremonia])).rows[0].estado, 'En curso');
    const estados = await mock.query('SELECT id_proceso, estado FROM public.proceso_grado_prueba ORDER BY id_proceso');
    assert.equal(estados.rows.find((row) => row.id_proceso === 'ficticio-posgrado-1').estado, 'Titulado');
    assert.equal(estados.rows.find((row) => row.id_proceso === 'ficticio-pregrado-2').estado, 'Pendiente');

    await app.query(
      "UPDATE public.proceso_grado_ceremonia SET estado_sincronizacion = 'Pendiente', id_proceso = 'ficticio-inexistente' WHERE id_graduando = $1",
      [graduandos.rows[0].id_graduando],
    );
    const error = await sync.sincronizarGradosPrueba();
    assert.equal(error.errores, 1);
    assert.equal((await app.query('SELECT estado_sincronizacion FROM public.proceso_grado_ceremonia WHERE id_graduando = $1', [graduandos.rows[0].id_graduando])).rows[0].estado_sincronizacion, 'Error');
    await app.query("UPDATE public.proceso_grado_ceremonia SET id_proceso = 'ficticio-posgrado-1' WHERE id_graduando = $1", [graduandos.rows[0].id_graduando]);
    assert.equal((await sync.sincronizarGradosPrueba()).actualizados, 1);
    assert.equal((await mock.query("SELECT estado FROM public.proceso_grado_prueba WHERE id_proceso = 'ficticio-pregrado-2'")).rows[0].estado, 'Pendiente');

    const manual = await app.query(
      `INSERT INTO public.ceremonia_grado (nombre, fecha, estado, periodo_grado, finalizar_automaticamente)
       VALUES ('Manual', CURRENT_DATE, 'Programada', '2026-2', TRUE) RETURNING id_ceremonia`,
    );
    const manualId = manual.rows[0].id_ceremonia;
    response = res();
    await controller.agregarCandidatoPrueba(request(manualId, { procesoId: 'ficticio-pregrado-2', programaId: 1 }), response);
    assert.equal(response.statusCode, 201);
    const manualSesion = await app.query(
      `INSERT INTO public.sesion (id_ceremonia, numero_sesion, nombre, estado, hora_inicio, hora_fin)
       VALUES ($1, 1, 'Manual', 'En curso', '08:00', '09:00') RETURNING id_sesion`, [manualId],
    );
    await app.query('UPDATE public.graduando SET id_sesion = $1 WHERE id_graduando = $2', [manualSesion.rows[0].id_sesion, Number(response.body.id)]);
    await app.query('INSERT INTO public.control_ingreso (id_sesion, id_graduando, ingreso) VALUES ($1, $2, TRUE)', [manualSesion.rows[0].id_sesion, Number(response.body.id)]);
    await app.query("UPDATE public.ceremonia_grado SET estado = 'En curso' WHERE id_ceremonia = $1", [manualId]);
    response = res();
    await operaciones.actualizarEstadoCeremonia(request(manualId, { estado: 'Finalizada' }), response);
    assert.equal(response.statusCode, 200);
    assert.equal((await sync.sincronizarGradosPrueba()).actualizados, 1);
    assert.equal((await mock.query("SELECT estado FROM public.proceso_grado_prueba WHERE id_proceso = 'ficticio-pregrado-2'")).rows[0].estado, 'Titulado');
    ejecutarScript('eliminarProcesosGradoPrueba.js');
    assert.equal((await mock.query('SELECT COUNT(*)::integer AS total FROM public.proceso_grado_prueba')).rows[0].total, 0);
    assert.equal((await app.query('SELECT COUNT(*)::integer AS total FROM public.graduando')).rows[0].total, 0);
  } finally {
    if (servicePool) await servicePool.end();
    if (fakePool) await fakePool.end();
    if (app) await app.end();
    if (mock) await mock.end();
    if (mockCreated) await admin.query(`DROP DATABASE ${pg.escapeIdentifier(mockName)}`);
    if (appCreated) await admin.query(`DROP DATABASE ${pg.escapeIdentifier(appName)}`);
    await admin.end();
  }
});
