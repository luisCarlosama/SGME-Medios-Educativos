-- Las ceremonias anteriores conservan la finalización manual.
ALTER TABLE public.ceremonia_grado
  ADD COLUMN IF NOT EXISTS periodo_grado VARCHAR(40),
  ADD COLUMN IF NOT EXISTS finalizar_automaticamente BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS public.catalogo_estado_grado (
  id_estado INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  elegible BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (nombre)
);

INSERT INTO public.catalogo_estado_grado (nombre, elegible)
VALUES ('Pendiente', TRUE), ('Titulado', FALSE)
ON CONFLICT (nombre) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.proceso_grado_ceremonia (
  id_graduando INTEGER PRIMARY KEY REFERENCES public.graduando (id_graduando),
  origen VARCHAR(40) NOT NULL,
  id_proceso VARCHAR(100) NOT NULL,
  estado_sincronizacion VARCHAR(20) NOT NULL DEFAULT 'Sin solicitar',
  error_sincronizacion TEXT
);
